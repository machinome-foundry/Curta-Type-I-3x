def bell_limit(turn):
    return piecewise(modulo(-turn, 360), BELL_ENVELOPE) - SOURCE_RADIUS


def collar_limit(lift):
    return piecewise(lift, COLLAR_ENVELOPE) - SOURCE_RADIUS


def radial_following(sources, target):
    def following(turn, lift, travel):
        lower, upper = bell_limit(turn), collar_limit(lift)
        return lower * (travel <= lower) + upper * (travel >= upper)
    return following

